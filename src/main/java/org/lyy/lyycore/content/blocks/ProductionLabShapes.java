    private static final VoxelShape[][] SHAPES = build();
    static VoxelShape get(Direction facing, int part) { return SHAPES[facing.get2DDataValue()][part]; }
    private static VoxelShape[][] build() {
        VoxelShape[][] shapes = new VoxelShape[4][45];
        for (int turn = 0; turn < 4; turn++) for (int part = 0; part < 45; part++) {
            int x = part % 5 - 2, z = part / 5 % 3 - 1, y = part / 15;
            VoxelShape shape = Shapes.empty();
            for (double[] box : BOXES) {
                double x0 = Math.max(0, box[0] - x), y0 = Math.max(0, box[1] - y), z0 = Math.max(0, box[2] - z);
                double x1 = Math.min(1, box[3] - x), y1 = Math.min(1, box[4] - y), z1 = Math.min(1, box[5] - z);
                if (x0 >= x1 || y0 >= y1 || z0 >= z1) continue;
                for (int step = 0; step < turn; step++) {
                    double oldX0 = x0, oldX1 = x1;
                    x0 = 1 - z1; x1 = 1 - z0; z0 = oldX0; z1 = oldX1;
                }
                shape = Shapes.or(shape, Shapes.box(x0, y0, z0, x1, y1, z1));
            }
            shapes[turn][part] = shape.optimize();
        }
        return shapes;
    }
